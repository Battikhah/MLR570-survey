#!/usr/bin/env python3
"""Generate paper/survey/supplement_methods.tex (Table S2) from docs/survey/included-methods.md.

    uv run python scripts/build_supplement.py

The markdown list is the source of truth; numbers are copied unchanged.
"""
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SRC = ROOT / "docs/survey/included-methods.md"
OUT = ROOT / "paper/survey/supplement_methods.tex"
_SPECIAL = {"&": r"\&", "%": r"\%", "#": r"\#", "_": r"\_", "$": r"\$", "^": r"\^{}", "~": r"\~{}",
            "→": r"$\to$", "τ": r"$\tau$", "×": r"$\times$", "α": r"$\alpha$", "β": r"$\beta$",
            "†": r"$^\dagger$", "\\": r"\textbackslash{}"}


def esc(text):
    text = text.strip().replace("\\dagger", "†")  # the markdown writes the dagger as TeX
    return "".join(_SPECIAL.get(ch, ch) for ch in text)


def rows(md):
    """(method, key, fam, venue, r8x4, w16, r18, mbv1, src, notes) for each numbered row."""
    out = []
    for line in md.splitlines():
        if not re.match(r"\|\s*\d+\s*\|", line):
            continue
        cells = [c.strip() for c in line.strip().strip("|").split("|")]
        key = re.search(r"registry `([^`]+)`", cells[-1])
        assert key, f"no registry key in row: {line[:60]}"
        out.append((cells[1], key.group(1), *cells[2:10]))
    return out


def tex_row(r):
    method, key, fam, venue, *vals, src, notes = r
    src = esc(src).replace(" T", "~T")  # tie "C T2" after escaping, so the ~ stays a TeX tie
    return " & ".join([f"{esc(method)}~\\citep{{{key}}}", fam, esc(venue), *vals, src, esc(notes)]) + r" \\"


def main():
    rs = rows(SRC.read_text(encoding="utf-8"))
    assert len(rs) == 112, len(rs)
    OUT.write_text("% generated by scripts/build_supplement.py from docs/survey/included-methods.md -- do not edit\n"
                   + "\n".join(tex_row(r) for r in rs) + "\n", encoding="utf-8")
    print(f"wrote {OUT.relative_to(ROOT)} ({len(rs)} rows)")


if __name__ == "__main__":
    main()
