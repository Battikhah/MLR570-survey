#!/usr/bin/env python3
"""Generate paper/survey/refs.bib from the literature registry and check survey citations.

    uv run python scripts/build_bib.py          # write refs.bib
    uv run python scripts/build_bib.py --check  # also fail on cite keys with no registry record

Every BibTeX key is the registry `id`. Records whose status is not published/accepted get a
note ("Preprint" / "Under review" / "Unverified record") so the text never presents them as
peer-reviewed; `--check` lists every cited record that is still `unverified`.
"""
import argparse
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "scripts"))
from build_literature_docs import records  # noqa: E402  (single registry loader)

SURVEY = ROOT / "paper/survey"
CITE = re.compile(r"\\(?:no)?cite[a-zA-Z]*\*?(?:\[[^\]]*\]){0,2}\{([^}]*)\}")
JOURNAL = re.compile(
    r"transactions|journal|\bJ\.|TMLR|TPAMI|IJCV|JMLR|Machine Learning with Applications|Letters",
    re.I,
)
NOTES = {"preprint": "Preprint", "under-review": "Under review", "unverified": "Unverified record"}


_SPECIAL = {"&": r"\&", "%": r"\%", "#": r"\#", "_": r"\_", "$": r"\$",
            "^": r"\^{}", "~": r"\~{}"}
COMMENT = re.compile(r"(?<!\\)%.*")  # TeX comment: unescaped % to end of line


def _esc(text):
    return "".join(_SPECIAL.get(ch, ch) for ch in str(text))


def entry(r):
    """One BibTeX entry for a registry record."""
    urls = r.get("urls") or {}
    ids = r.get("identifiers") or {}
    venue = r.get("venue")
    status = r.get("status")
    if r.get("type") == "repository" or not venue or venue == "arXiv":
        kind, venue_field = "misc", None
    elif JOURNAL.search(venue):
        kind, venue_field = "article", ("journal", venue)
    else:
        kind, venue_field = "inproceedings", ("booktitle", venue)
    fields = [
        ("title", "{" + _esc(r["title"]) + "}"),  # double braces keep capitalisation
        ("author", " and ".join(_esc(a) for a in (r.get("authors") or ["Anonymous"]))),
        ("year", str(r.get("date") or "")[:4] or "n.d."),
    ]
    if venue_field:
        fields.append((venue_field[0], _esc(venue_field[1])))
    if ids.get("doi"):
        fields.append(("doi", ids["doi"]))
    if ids.get("arxiv"):
        fields += [("eprint", ids["arxiv"]), ("archivePrefix", "arXiv")]
    url = urls.get("official") or urls.get("arxiv") or urls.get("code")
    if url:
        fields.append(("url", url))
    if status in NOTES:
        fields.append(("note", NOTES[status]))
    body = ",\n".join(f"  {k} = {{{v}}}" for k, v in fields)
    return f"@{kind}{{{r['id']},\n{body}\n}}\n"


def cited_keys(tex_root):
    keys = set()
    for path in sorted(Path(tex_root).rglob("*.tex")):
        if "tmlr" in path.parts:  # vendored template example
            continue
        text = COMMENT.sub("", path.read_text(encoding="utf-8"))
        for group in CITE.findall(text):
            keys.update(k.strip() for k in group.split(",") if k.strip())
    return keys


def check(recs, tex_root):
    """Return (missing keys, cited unverified keys)."""
    by_id = {r["id"]: r for r in recs}
    cited = cited_keys(tex_root)
    missing = sorted(k for k in cited if k not in by_id)
    unverified = sorted(k for k in cited if k in by_id and by_id[k].get("status") == "unverified")
    return missing, unverified


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument(
        "--check", action="store_true", help="fail on cite keys missing from the registry"
    )
    args = ap.parse_args(argv)
    recs = records()
    ids = [r["id"] for r in recs]
    dupes = sorted({i for i in ids if ids.count(i) > 1})
    if dupes:
        print(f"duplicate registry ids: {', '.join(dupes)}", file=sys.stderr)
        return 1
    out = SURVEY / "refs.bib"
    out.write_text(
        "% generated by scripts/build_bib.py from literature/*.yaml -- do not edit\n\n"
        + "\n".join(entry(r) for r in recs),
        encoding="utf-8",
    )
    print(f"wrote {out.relative_to(ROOT)} ({len(recs)} entries)")
    if args.check:
        missing, unverified = check(recs, SURVEY)
        for k in unverified:
            print(f"cited but unverified (qualify in text): {k}")
        if missing:
            print(f"cite keys with no registry record: {', '.join(missing)}", file=sys.stderr)
            return 1
        print("citation check OK")
    return 0


if __name__ == "__main__":
    sys.exit(main())
