"""Fig. 5 of the survey: the direction five two-objective rules pick for one pair of gradients.

Run from the repo root:  uv run --frozen python paper/survey/figures/moo_geometry.py
It rewrites paper/survey/figures/moo_geometry.tex (TikZ, \\input by sections/06a_moo.tex).
tests/unit/test_moo_geometry.py recomputes every direction independently.

Each rule follows its paper (equation numbers in the docstrings). g1 is the primary (task) gradient
where a rule has a primary; the vectors are illustrative, not measured.
"""

from __future__ import annotations

import math
from pathlib import Path

import numpy as np

G1 = np.array([2.0, 0.5])  # primary / task gradient
G2 = np.array([-0.5, 0.8])  # secondary / distillation gradient; G1 . G2 = -0.6 < 0 (conflict)
CAGRAD_C = 0.5
PCD_TAU = 0.5
OUT = Path(__file__).with_suffix(".tex")


def weighted_sum(g1: np.ndarray, g2: np.ndarray, w: float = 0.5) -> np.ndarray:
    """Linear scalarisation with weights (w, 1 - w)."""
    return w * g1 + (1.0 - w) * g2


def mgda(g1: np.ndarray, g2: np.ndarray) -> np.ndarray:
    """Sener & Koltun (2018) Eq. (4): two-task min-norm hull point, alpha clipped to [0, 1]."""
    diff = g1 - g2
    alpha = float(np.clip(((g2 - g1) @ g2) / (diff @ diff), 0.0, 1.0))
    return alpha * g1 + (1.0 - alpha) * g2


def pcgrad(g1: np.ndarray, g2: np.ndarray) -> np.ndarray:
    """Yu et al. (2020) Alg. 1: on conflict, project each gradient onto the other's normal plane."""
    p1 = g1 - min(0.0, g1 @ g2) / (g2 @ g2) * g2
    p2 = g2 - min(0.0, g2 @ g1) / (g1 @ g1) * g1
    return p1 + p2


def cagrad(g1: np.ndarray, g2: np.ndarray, c: float = CAGRAD_C) -> np.ndarray:
    """Liu et al. (2021) Alg. 1: g0 = mean gradient, phi = c^2 |g0|^2,
    w* = argmin_{w in simplex} g_w . g0 + sqrt(phi) |g_w|,  d = g0 + sqrt(phi) / |g_w| g_w."""
    g0 = 0.5 * (g1 + g2)
    sphi = c * float(np.linalg.norm(g0))

    def f(w: float) -> float:
        gw = w * g1 + (1.0 - w) * g2
        return float(gw @ g0 + sphi * np.linalg.norm(gw))

    lo, hi = 0.0, 1.0  # F is convex in w; ternary search on [0, 1]
    for _ in range(200):
        m1, m2 = lo + (hi - lo) / 3, hi - (hi - lo) / 3
        lo, hi = (lo, m2) if f(m1) <= f(m2) else (m1, hi)
    w = 0.5 * (lo + hi)
    gw = w * g1 + (1.0 - w) * g2
    return g0 + sphi / float(np.linalg.norm(gw)) * gw


def pcd(g1: np.ndarray, g2: np.ndarray, tau: float = PCD_TAU) -> np.ndarray:
    """Varam & AlHajri (2026) Cor. 4.6 / Eq. (14), with normalisation scales set to 1:
    d = g1 + max(0, tau - g1.g2 / |g2|^2) g2."""
    return g1 + max(0.0, tau - (g1 @ g2) / (g2 @ g2)) * g2


def directions(g1: np.ndarray = G1, g2: np.ndarray = G2) -> dict[str, np.ndarray]:
    return {
        "Weighted sum": weighted_sum(g1, g2),
        "MGDA": mgda(g1, g2),
        "PCGrad": pcgrad(g1, g2),
        "CAGrad": cagrad(g1, g2),
        "PCD": pcd(g1, g2),
    }


STYLE = {  # colour-blind-safe Okabe-Ito hues; dash patterns keep it readable in greyscale
    "Weighted sum": ("{rgb,255:red,0;green,114;blue,178}", "solid"),
    "MGDA": ("{rgb,255:red,213;green,94;blue,0}", "dashed"),
    "PCGrad": ("{rgb,255:red,0;green,158;blue,115}", "dotted"),
    "CAGrad": ("{rgb,255:red,204;green,121;blue,167}", "dashdotted"),
    "PCD": ("{rgb,255:red,230;green,159;blue,0}", "densely dashed"),
}


def _pt(v: np.ndarray) -> str:
    return f"({v[0]:.4f},{v[1]:.4f})"


def tikz(g1: np.ndarray = G1, g2: np.ndarray = G2) -> str:
    d = directions(g1, g2)
    lines = [
        "% Generated by paper/survey/figures/moo_geometry.py -- do not edit by hand.",
        f"% g1 = {g1.tolist()}, g2 = {g2.tolist()}, CAGrad c = {CAGRAD_C}, PCD tau = {PCD_TAU}",
        *(f"% {k}: {_pt(v)}" for k, v in d.items()),
        "\\begin{tikzpicture}[scale=1.9,>=stealth]",
        "\\draw[gray!40,very thin] (-1,-0.5) grid[step=0.5] (2.5,2);",
        "\\draw[gray!70] (-1,0) -- (2.5,0); \\draw[gray!70] (0,-0.5) -- (0,2);",
        # PCD constraint boundary {d : g2.d = tau |g2|^2}, a line orthogonal to g2
        _boundary(g2),
        f"\\draw[->,very thick,black] (0,0) -- {_pt(g1)} node[below right] {{$g_1$ (task)}};",
        f"\\draw[->,very thick,gray] (0,0) -- {_pt(g2)} node[above left] {{$g_2$ (KD)}};",
    ]
    for name, v in d.items():
        colour, dash = STYLE[name]
        lines.append(f"\\draw[->,thick,color={colour},{dash}] (0,0) -- {_pt(v)};")
    # legend
    for i, name in enumerate(d):
        colour, dash = STYLE[name]
        y = 1.9 - 0.25 * i
        lines.append(
            f"\\draw[thick,color={colour},{dash}] (1.75,{y:.2f}) -- (2.1,{y:.2f}) "
            f"node[right,black,font=\\scriptsize] {{{name}}};"
        )
    lines.append("\\end{tikzpicture}")
    return "\n".join(lines) + "\n"


def _boundary(g2: np.ndarray) -> str:
    base = PCD_TAU * g2  # the point on the boundary closest to the origin
    t = np.array([g2[1], -g2[0]]) / float(np.linalg.norm(g2))
    a, b = base - 0.9 * t, base + 1.8 * t
    return (
        f"\\draw[densely dotted,gray] {_pt(a)} node[below right,font=\\scriptsize] "
        f"{{$g_2^\\top d=\\tau\\|g_2\\|^2$}} -- {_pt(b)};"
    )


if __name__ == "__main__":
    OUT.write_text(tikz())
    for k, v in directions().items():
        print(f"{k:13s} {v.round(4)}  angle={math.degrees(math.atan2(v[1], v[0])):.1f} deg")
    print(f"wrote {OUT}")
